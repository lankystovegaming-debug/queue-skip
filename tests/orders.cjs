const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../assets/orders.js'),'utf8'),context);
const orders=context.window.demoOrders;
const draft={studentName:'Demo Student',studentClass:'3A',pickupDate:'2026-11-07',pickupTime:'10:30',notes:'Less chilli',paymentMethod:'online',lastFour:'4242',number:'4242424242424242',cvv:'123',holder:'Demo Cardholder',expiry:'11/27',items:[{stall:'Golden Grain',unit:'01',name:'Chicken Rice',quantity:2,price:450},{stall:'Kopi Kakis',unit:'05',name:'Kopi',quantity:1,price:150}]};
const order=orders.create(draft,'QS-DEMO-AB12CD34','2026-11-06T03:00:00Z');
assert.equal(order.total,1050);
const raw=JSON.stringify(order);
for(const key of ['number','cvv','holder','expiry']) assert.equal(Object.hasOwn(order,key),false,key);
assert.equal(raw.includes('4242424242424242'),false);
assert.equal(orders.parse(raw).id,order.id);
assert.equal(orders.parse(raw).items.length,2);
assert.equal(orders.create({...draft,paymentMethod:'pickup'},order.id,order.createdAt).lastFour,'');
for(const raw of [null,'','not JSON','{}','[]',JSON.stringify({...order,total:1}),JSON.stringify({...order,items:[]}),JSON.stringify({...order,items:[{...order.items[0],quantity:0}]}),JSON.stringify({...order,paymentMethod:'other'}),JSON.stringify({...order,lastFour:'123456789'})]) assert.equal(orders.parse(raw),null,String(raw));
const sanitized=orders.parse(JSON.stringify({...order,number:'4242424242424242',cvv:'123'}));
assert.equal(Object.hasOwn(sanitized,'number'),false);
assert.equal(Object.hasOwn(sanitized,'cvv'),false);
console.log('Passed receipt checks: totals, round-trip storage, malformed data, tampering, and exclusion of card details.');
